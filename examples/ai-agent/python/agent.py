import os
import asyncio
from fastapi import FastAPI, Form, Request, Header, HTTPException, BackgroundTasks, Response
from twilio.rest import Client
from twilio.request_validator import RequestValidator

app = FastAPI(title="AI Support Agent")

TWILIO_ACCOUNT_SID = os.getenv("TWILIO_ACCOUNT_SID", "AC00000000000000000000000000000001")
TWILIO_AUTH_TOKEN = os.getenv("TWILIO_AUTH_TOKEN", "authtoken")
TWILIO_API_BASE = os.getenv("TWILIO_API_BASE", "http://127.0.0.1:8080")
TWILIO_PHONE_NUMBER = os.getenv("TWILIO_PHONE_NUMBER", "+14155550199")

# Configure Twilio REST SDK to talk to local omnic
twilio_client = Client(
    TWILIO_ACCOUNT_SID,
    TWILIO_AUTH_TOKEN,
    api_endpoint_factory=lambda: TWILIO_API_BASE,
)
validator = RequestValidator(TWILIO_AUTH_TOKEN)


async def run_ai_reasoning_and_reply(user_number: str, query: str):
    """Simulate LLM / tool call reasoning taking some time."""
    await asyncio.sleep(1.5)

    response_text = f"AI Agent: I received your message '{query}'. Your request is being handled."

    # Send asynchronous SMS back to the handset via omnic REST API
    twilio_client.messages.create(
        to=user_number,
        from_=TWILIO_PHONE_NUMBER,
        body=response_text,
        status_callback="http://127.0.0.1:8000/api/sms/status",
    )


@app.post("/api/sms/inbound")
async def handle_inbound_sms(
    request: Request,
    background_tasks: BackgroundTasks,
    From: str = Form(...),
    To: str = Form(...),
    Body: str = Form(...),
    x_twilio_signature: str = Header(None),
):
    # Verify cryptographic signature generated by omnic
    url = str(request.url)
    form_data = await request.form()
    params = dict(form_data)
    if x_twilio_signature and not validator.validate(url, params, x_twilio_signature):
        raise HTTPException(status_code=403, detail="Invalid Twilio signature")

    # Fast synchronous TwiML response for ping checks
    if Body.strip().upper() == "PING":
        return Response(
            content="<Response><Message>PONG</Message></Response>",
            media_type="application/xml",
        )

    # For AI agent conversational queries, schedule background work and return empty 200 OK
    background_tasks.add_task(run_ai_reasoning_and_reply, From, Body)
    return Response(content="<Response/>", media_type="application/xml")


@app.post("/api/sms/status")
async def handle_status_callback(
    MessageSid: str = Form(...),
    MessageStatus: str = Form(...),
):
    print(f"Delivery update for {MessageSid}: {MessageStatus}")
    return {"status": "ok"}


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="127.0.0.1", port=8000)
